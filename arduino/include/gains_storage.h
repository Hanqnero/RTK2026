#pragma once

#include <stdint.h>

#include "wheel_controller.h"

// Хранение коэффициентов колёс в EEPROM.
//
// Зачем это нужно именно здесь: настройка выполняется стендовым скриптом
// по serial, а ROS-мост коэффициенты не проталкивает. Без энергонезависимого
// хранения каждое выключение питания возвращало бы прошивку к скомпилированным
// значениям, и результат настройки терялся бы вместе с ним.
//
// Формат записи по адресу 0:
//
//     magic   u32  = 0x524B3257
//     version u8   = 1
//     left    WheelGains (5 float)
//     right   WheelGains (5 float)
//     crc16   u16  по всем предыдущим байтам
//
// CRC нужна не от помех, а от частично записанной или никогда не
// инициализированной EEPROM: чистая память читается как 0xFF, что дало бы
// NaN во всех коэффициентах и мгновенно испортило бы регулятор.

struct StoredGains {
    WheelGains left;
    WheelGains right;
};

enum class GainsLoadResult : uint8_t {
    // Запись прочитана и проверена.
    Ok = 0,
    // Magic не совпал: EEPROM пуста или занята чем-то другим.
    NotInitialised = 1,
    // Magic совпал, но версия формата другая.
    VersionMismatch = 2,
    // Не сошлась CRC.
    CorruptedChecksum = 3,
    // Проверка прошла, но среди коэффициентов есть NaN или бесконечность.
    InvalidValues = 4,
};

// Прочитать коэффициенты из EEPROM.
//
// Значение по указателю изменяется только при результате Ok, поэтому
// вызывающий код может заранее положить туда скомпилированные значения
// по умолчанию и использовать их как запасной вариант.
GainsLoadResult loadGains(StoredGains* out);

// Записать коэффициенты в EEPROM.
//
// Используется EEPROM.update, поэтому неизменившиеся байты не переписываются:
// ресурс ячейки около ста тысяч циклов, а настройка перезаписывает запись
// десятки раз за сеанс.
//
// :returns: true, если запись прошла и последующее чтение её подтвердило.
bool saveGains(const StoredGains& gains);

// Признать сохранённую запись недействительной.
// Следующий loadGains вернёт NotInitialised, и прошивка возьмёт значения
// по умолчанию из motor_interface.h.
void clearStoredGains();
