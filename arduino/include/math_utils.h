// Мелкие числовые помощники, нужные и контуру управления, и main.cpp.
// Вынесены в общий заголовок, чтобы две копии не разошлись в поведении
// на границах диапазона.

// Ограничение значения диапазоном [low, high].
//
// NaN не проходит ни одно из сравнений и возвращается как есть. Это
// сознательно: подмена NaN нулём здесь спрятала бы источник проблемы,
// поэтому вход проверяется там, где он появляется, - при разборе команды.
inline float clampFloat(float value, float low, float high) {
    if (value < low) {
        return low;
    }
    if (value > high) {
        return high;
    }
    return value;
}

// Знак числа: -1, 0 или +1. Ноль возвращается именно для нуля, чтобы
// feedforward не подавал статическую составляющую при нулевой уставке.
inline float signOf(float value) {
    if (value > 0.0f) {
        return 1.0f;
    }
    if (value < 0.0f) {
        return -1.0f;
    }
    return 0.0f;
}
