#pragma once

#include <stdint.h>

// Неблокирующее поочерёдное измерение шести ультразвуковых
// дальномеров.
//
// Прошивка только измеряет и отдаёт результат в телеметрии. Решение об
// остановке принимает Raspberry Pi: там же работает Nav2, который обязан
// видеть препятствие как часть общей картины, а не узнавать о нём постфактум
// по внезапно остановившемуся роботу.
//
// Почему измерение сделано автоматом состояний:
//
// pulseIn блокирует до kSonarEchoTimeoutUs, то есть до 25 мс - это весь
// управляющий цикл целиком. Решение, принимаемое не здесь, само по себе
// блокировку не убирает: пока MCU мерит, он и блокируется.
//
// Здесь запуск импульса занимает 10 микросекунд, а ожидание эха размазано
// по обычным итерациям loop(), которых между управляющими циклами тысячи.

void configureSonar();

// Продвинуть измерение. Вызывается из loop() как можно чаще.
void updateSonar();

constexpr uint8_t kSonarCount = 6U;

struct SonarReading {
    // Индекс 0..5 в том же порядке, что и пары пинов.
    uint8_t sensor_index;
    // Отрицательное значение означает таймаут эха.
    float distance_cm;
};

// Забрать завершённый замер. Каждый замер возвращается ровно один
// раз; false означает, что updateSonar ещё ждёт эхо.
bool sonarTakeCompletedReading(SonarReading* reading);

// Дистанция последнего успешного измерения в сантиметрах.
// Отрицательное значение означает, что эхо не вернулось в пределах таймаута.
float sonarLastDistanceCm();

// Суммарное время, проведённое внутри updateSonar с момента прошлого чтения.
// Обнуляется при чтении. Величина уходит в StatsPayload и служит
// доказательством отсутствия блокировки: измерение построено автоматом
// состояний, поэтому за цикл здесь набегают единицы микросекунд.
uint32_t sonarTakeLastBlockUs();
